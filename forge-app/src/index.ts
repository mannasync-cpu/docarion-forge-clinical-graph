/**
 * Atlassian Forge MCP Server Webtrigger (JSON-RPC 2.0 over HTTP)
 */
export async function handleAtlassianMcpRequest(req: { body: string }) {
  const rpc = JSON.parse(req.body || '{}');
  if (rpc.method === 'tools/list') {
    return {
      statusCode: 200,
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        jsonrpc: '2.0',
        id: rpc.id ?? 1,
        result: {
          tools: [
            {
              name: 'query_clinical_teamwork_graph',
              description: 'Traverse Atlassian Teamwork Graph for linked Jira incidents, Confluence SOPs, biomedical assets, and on-call teams.',
              inputSchema: { type: 'object', properties: { issueKey: { type: 'string' } }, required: ['issueKey'] },
            },
            {
              name: 'triage_hospital_jsm_incident',
              description: 'Audit NEWS2 acuity & SLA timers and escalate Jira Service Management priority.',
              inputSchema: { type: 'object', properties: { issueKey: { type: 'string' } }, required: ['issueKey'] },
            },
            {
              name: 'attach_confluence_clinical_sop',
              description: 'Attach hospital-approved Confluence SOP protocol checklist to a Jira incident.',
              inputSchema: { type: 'object', properties: { issueKey: { type: 'string' } }, required: ['issueKey'] },
            },
            {
              name: 'generate_sbar_handoff',
              description: 'Generate structured Situation-Background-Assessment-Recommendation (SBAR) specialist handoff.',
              inputSchema: { type: 'object', properties: { issueKey: { type: 'string' } }, required: ['issueKey'] },
            },
            {
              name: 'create_confluence_capa_report',
              description: 'Draft a compliant Confluence CAPA Root-Cause Postmortem linked in Teamwork Graph.',
              inputSchema: { type: 'object', properties: { issueKey: { type: 'string' } }, required: ['issueKey'] },
            },
          ],
        },
      }),
    };
  }

  return {
    statusCode: 200,
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      jsonrpc: '2.0',
      id: rpc.id ?? 1,
      result: {
        executedTool: rpc.params?.name || rpc.method,
        arguments: rpc.params?.arguments || {},
        hipaaSafeHarbor: 'ENFORCED_ZERO_RAW_PHI',
        timestamp: new Date().toISOString(),
      },
    }),
  };
}
